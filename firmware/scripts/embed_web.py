"""PlatformIO pre-build script: embed data/index.html in the firmware.

Gzips the page and writes it as a C array to
.pio/generated/WebIndexHtml.h, which src/WebInterface.cpp includes. The
header is only rewritten when the page changes, so unrelated builds stay
incremental. Edit data/index.html and build/upload as normal - there is no
separate filesystem upload step.
"""

import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
source = os.path.join(project_dir, "data", "index.html")
out_dir = os.path.join(project_dir, ".pio", "generated")
target = os.path.join(out_dir, "WebIndexHtml.h")

with open(source, "rb") as f:
    html = f.read()

# mtime=0 keeps the output byte-identical for identical input.
compressed = gzip.compress(html, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(compressed), 16):
    chunk = compressed[i:i + 16]
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

header = (
    "// Generated by scripts/embed_web.py from data/index.html - do not edit.\n"
    "#pragma once\n"
    "#include <stddef.h>\n"
    "#include <stdint.h>\n\n"
    f"// {len(html)} bytes, {len(compressed)} gzipped\n"
    "static const uint8_t WEB_INDEX_HTML_GZ[] = {\n"
    + "\n".join(lines)
    + "\n};\n"
    "static const size_t WEB_INDEX_HTML_GZ_LEN = sizeof(WEB_INDEX_HTML_GZ);\n"
)

os.makedirs(out_dir, exist_ok=True)
existing = None
if os.path.exists(target):
    with open(target, "r", encoding="utf-8") as f:
        existing = f.read()
if existing != header:
    with open(target, "w", encoding="utf-8") as f:
        f.write(header)
    print(f"embed_web: data/index.html -> {len(compressed)} bytes gzipped")

env.Append(CPPPATH=[out_dir])  # noqa: F821
